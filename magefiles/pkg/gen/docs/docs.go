// Package docs runs every generator the book is built from: the two pages copied in from
// outside docs/ (book.go), and the table of contents compiled from the result (summary.go).
package docs

// generatedBanner marks a page as generator output, so that an editor who opens one is told
// before they change it that their change will not survive the next commit. Shared by book.go
// and any generator added beside it.
const generatedBanner = "<!-- Page generated by mage; DO NOT EDIT -->"

// GenerateDocument regenerates every part of the book that is written from something else.
//
// Order matters: the summary is compiled from what is on disk, so it has to run last or it
// describes the previous run's tree. A generator added here goes above generateSummary for the
// same reason.
func GenerateDocument() error {
	if err := generateBookPages(); err != nil {
		return err
	}

	return generateSummary()
}
